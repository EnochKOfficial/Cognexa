import { useMemo, useState } from 'react'
import { Award, Check, Download, ListChecks, RotateCcw, X } from 'lucide-react'
import type { Question, StudyMaterial } from '../../types/api'
import { downloadTextFile, slugify } from '../../lib/export'

/** Build the downloadable revision-questions text file. */
export function buildQuestionsText(result: StudyMaterial): string {
  const lines: string[] = []
  lines.push(`Cognexa — Revision Questions: ${result.main_topic.label}`)
  lines.push(
    result.is_demo
      ? '(DEMO DATA — mock generation, no AI model was invoked)'
      : '(AI-generated with Gemma 4 via Google AI Studio)',
  )
  lines.push('')
  result.questions.forEach((question, index) => {
    lines.push(`${index + 1}. ${question.question}`)
    question.options.forEach((option, optionIndex) => {
      lines.push(`   ${String.fromCharCode(65 + optionIndex)}) ${option}`)
    })
    lines.push('')
  })
  lines.push('—'.repeat(48))
  lines.push('ANSWER KEY')
  result.questions.forEach((question: Question, index) => {
    lines.push(`${index + 1}. ${question.correct_answer}`)
    lines.push(`   Why: ${question.explanation}`)
  })
  return lines.join('\n')
}

export default function QuizTab({ result }: { result: StudyMaterial }) {
  const [answers, setAnswers] = useState<Record<string, string>>({})
  const [submitted, setSubmitted] = useState(false)

  const questions = result.questions
  const answeredCount = Object.keys(answers).filter((id) =>
    questions.some((question) => question.id === id),
  ).length
  const allAnswered = answeredCount === questions.length

  const score = useMemo(() => {
    return questions.reduce(
      (total, question) => total + (answers[question.id] === question.correct_answer ? 1 : 0),
      0,
    )
  }, [answers, questions])

  const percentage = questions.length > 0 ? Math.round((score / questions.length) * 100) : 0

  const handleDownload = () => {
    downloadTextFile(
      `${slugify(result.main_topic.label)}-revision-questions.txt`,
      buildQuestionsText(result),
    )
  }

  const resetQuiz = () => {
    setAnswers({})
    setSubmitted(false)
  }

  const gradeLabel =
    percentage >= 80 ? 'Excellent — you know this page!' : percentage >= 50 ? 'Good progress — review the misses below.' : 'Keep going — reread the summary and try again.'

  return (
    <div>
      {/* Toolbar */}
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
        <p className="text-xs text-muted">
          {result.is_demo
            ? `${questions.length} revision questions from the mock generator — demo content.`
            : `${questions.length} revision questions generated by Gemma 4 from your page.`}
        </p>
        <button type="button" onClick={handleDownload} className="btn-secondary px-3 py-2 text-xs">
          <Download className="h-3.5 w-3.5" aria-hidden="true" />
          Download questions (.txt)
        </button>
      </div>

      {/* Score banner */}
      {submitted && (
        <div
          role="status"
          className="card mb-6 flex flex-col items-center gap-2 bg-gradient-to-r from-accent/12 to-blue/12 p-6 text-center sm:flex-row sm:justify-between sm:text-left"
        >
          <div className="flex items-center gap-4">
            <span className="flex h-14 w-14 shrink-0 items-center justify-center rounded-2xl bg-success/15">
              <Award className="h-7 w-7 text-success" aria-hidden="true" />
            </span>
            <div>
              <p className="text-2xl font-bold text-white">
                {score} / {questions.length}
                <span className="ml-2 text-base font-medium text-muted">({percentage}%)</span>
              </p>
              <p className="mt-0.5 text-sm text-muted">{gradeLabel}</p>
            </div>
          </div>
          <button type="button" onClick={resetQuiz} className="btn-secondary shrink-0">
            <RotateCcw className="h-4 w-4" aria-hidden="true" />
            Try again
          </button>
        </div>
      )}

      {/* Questions */}
      <ol className="space-y-5">
        {questions.map((question, index) => {
          const selected = answers[question.id]
          const isCorrect = selected === question.correct_answer
          return (
            <li key={question.id} className="card p-6">
              <div className="mb-4 flex items-start gap-3">
                <span className="mt-0.5 flex h-7 w-7 shrink-0 items-center justify-center rounded-lg bg-accent/15 text-xs font-bold text-accent-strong">
                  {index + 1}
                </span>
                <h3 className="font-semibold leading-snug text-white">{question.question}</h3>
              </div>

              <div role="group" aria-label={`Answer options for question ${index + 1}`} className="grid gap-2.5 sm:grid-cols-2">
                {question.options.map((option, optionIndex) => {
                  const optionLetter = String.fromCharCode(65 + optionIndex)
                  const isSelected = selected === option
                  const showCorrect = submitted && option === question.correct_answer
                  const showWrong = submitted && isSelected && !isCorrect
                  return (
                    <button
                      key={option}
                      type="button"
                      disabled={submitted}
                      aria-pressed={isSelected}
                      onClick={() =>
                        setAnswers((current) => ({ ...current, [question.id]: option }))
                      }
                      className={`flex items-center gap-3 rounded-xl border px-4 py-3 text-left text-sm transition-colors duration-150 ${
                        showCorrect
                          ? 'border-success/60 bg-success-dim text-slate-100'
                          : showWrong
                            ? 'border-danger/60 bg-danger-dim text-slate-100'
                            : isSelected
                              ? 'border-accent/70 bg-accent/15 text-white'
                              : 'border-line bg-navy-900/50 text-slate-300 hover:border-line-strong hover:bg-navy-800/60'
                      } ${submitted ? 'cursor-default' : 'cursor-pointer'}`}
                    >
                      <span
                        className={`flex h-6 w-6 shrink-0 items-center justify-center rounded-md border text-[11px] font-bold ${
                          isSelected
                            ? 'border-accent/70 bg-accent/25 text-accent-strong'
                            : 'border-line-strong text-muted'
                        }`}
                        aria-hidden="true"
                      >
                        {optionLetter}
                      </span>
                      <span className="flex-1">{option}</span>
                      {showCorrect && <Check className="h-4 w-4 shrink-0 text-success" aria-hidden="true" />}
                      {showWrong && <X className="h-4 w-4 shrink-0 text-danger" aria-hidden="true" />}
                    </button>
                  )
                })}
              </div>

              {submitted && (
                <div
                  className={`mt-4 rounded-xl border px-4 py-3 text-sm leading-relaxed ${
                    isCorrect
                      ? 'border-success/30 bg-success-dim/60 text-slate-300'
                      : 'border-danger/30 bg-danger-dim/60 text-slate-300'
                  }`}
                >
                  <p className="mb-1 font-semibold">
                    {isCorrect ? (
                      <span className="text-success">Correct</span>
                    ) : (
                      <span className="text-danger">
                        Not quite — the answer is “{question.correct_answer}”
                      </span>
                    )}
                  </p>
                  <p className="text-muted">{question.explanation}</p>
                </div>
              )}
            </li>
          )
        })}
      </ol>

      {/* Submit */}
      {!submitted && (
        <div className="mt-6 flex flex-col items-center gap-3 sm:flex-row sm:justify-between">
          <p className="text-xs text-muted">
            <ListChecks className="mr-1.5 inline h-3.5 w-3.5" aria-hidden="true" />
            {answeredCount} of {questions.length} answered
            {!allAnswered && ' — answer every question to submit'}
          </p>
          <button
            type="button"
            onClick={() => setSubmitted(true)}
            disabled={!allAnswered}
            className="btn-primary px-6 py-3"
          >
            Submit answers
          </button>
        </div>
      )}
    </div>
  )
}
